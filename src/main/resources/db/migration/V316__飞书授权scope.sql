-- V316 · 记下「这次授权到底拿到了哪些 scope」
--
-- ══════════════════════════════════════════════════════════════════════════
-- 一、为什么需要它
-- ══════════════════════════════════════════════════════════════════════════
-- 一个飞书应用的能力不是固定的：权限（scope）由管理员在开放平台审批，
-- 我们这边也会随着功能增加**扩 DEFAULT_SCOPE**（比如读历史消息要
-- `im:message.group_msg:get_as_user`、`search:message`）。
--
-- 问题在于：**user token 里带的是「授权那一刻」的 scope**。
-- 应用后来加了权限、但我们手上这张旧 token 不会自动获得 ⇒
-- 表现为「代码看起来对、一调就读权限错」，而用户完全不知道要去重新授权。
--
-- 飞书的 device flow token 响应**会返回 `scope` 字段**（授权实际授予的集合），
-- 所以把它存下来，就能在「打开飞书渠道」时比对：
--   当前 token 的 scope ⊉ 我们需要的 scope ⇒ 提示「需要重新授权以启用新能力」
-- 而不是等某次调用失败才暴露。
--
-- ══════════════════════════════════════════════════════════════════════════
-- 二、为什么是空格分隔的字符串而不是 JSON 数组
-- ══════════════════════════════════════════════════════════════════════════
-- 飞书返回的就是空格分隔的串（如 `im:message im:message.send_as_user offline_access`），
-- 原样存下来：① 排障时能直接看 ② 比对时按空格切开即可，不需要解析/序列化一层。
-- ⛔ 不要在这里做归一化（排序/去重）——原样保留才能和飞书对账。
--
-- 可空：历史数据（V313 之前授权的实例）没有它 ⇒ 读侧按「未知」处理，
-- 未知时的策略是**当作可能不全**（提示用户重新授权一次，代价极小）。

ALTER TABLE im_channel_instance ADD COLUMN user_scope TEXT;
