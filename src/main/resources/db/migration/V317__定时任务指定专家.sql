-- V317 · 定时任务可以指定「专家」（主线程 agent）
--
-- ══════════════════════════════════════════════════════════════════════════
-- 一、为什么需要这一列
-- ══════════════════════════════════════════════════════════════════════════
-- 「专家」在仓里 = 主线程 agent（`sessions.main_thread_agent`，V58），
-- 它在 `LlmAgentLoop.buildEffectivePromptOptions` 里被读成 `mainThreadAgentDefinition`，
-- 进而替换系统提示词（对齐 CC `appState.agent` + `resumeAgent.ts:121-124`）。
--
-- 现状缺口（用户 2026-11-19 指出）：**只有「新建会话」时能选专家，定时任务选不了**。
-- 一个「每天 9 点用某个专家做某件事」的任务，实际跑起来用的是那个会话原本的专家，
-- 或者压根没有专家。
--
-- ══════════════════════════════════════════════════════════════════════════
-- 二、为什么存任务上，而不是「执行时改会话的 main_thread_agent」
-- ══════════════════════════════════════════════════════════════════════════
-- 会话列是**用户的持久设置**：用户手动打开那个会话时，期望看到的是自己选的专家。
-- 如果任务执行时把它改掉（哪怕是临时改再改回来），会带来两个问题：
--   · 并发：任务跑的同时用户可能正打开该会话 ⇒ 看到「专家被换了」
--   · 崩了回不去：进程在任务执行中挂掉，会话就永久停在任务指定的专家上
-- ⇒ 所以必须在**轮次级别**覆盖（`RunRequest` 一路带下去，只影响这一轮），
--    不写会话列。这与 `notifyChats` 的处理方式同源（`RunRequest.withNotifyChats`）。
--
-- 可空：null = 不指定（沿用会话列，与改动前行为完全一致）。

ALTER TABLE schedules ADD COLUMN main_thread_agent TEXT;
