--   其它值 → 400。因 update 是 null=不覆盖的 merge 语义，清列必须走
--   update(entity, false) 显式写 NULL（同 subagent_default_runtime 先例）。
-- 映射：Java 字段 crossSessionInbound ↔ 列 cross_session_inbound
--   （MyBatis-Flex camelCase→snake 自动映射）。
