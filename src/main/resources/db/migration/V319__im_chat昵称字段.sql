-- V319 · im_chat 增加「昵称」列，与 peer_name 并存
--
-- ══════════════════════════════════════════════════════════════════════════
-- 一、为什么要新列而不是改 peer_name
-- ══════════════════════════════════════════════════════════════════════════
-- peer_name 现在混着三种东西：群名、对方显示名、以及「实在不知道是谁」时
-- 退化成的平台 id。用户要的是**对方改过的昵称**（人读的名字），
-- 而 peer_name 已经承载了历史数据与「列表标题」语义，直接改列名要迁移存量 + 回归
-- 所有读它的地方。
-- ⇒ 新增 nick_name：**存平台给的昵称**；peer_name 保持原样（读侧优先用新列，回退旧列）。
--
-- ══════════════════════════════════════════════════════════════════════════
-- 二、值从哪来（三平台差异，别指望都有）
-- ══════════════════════════════════════════════════════════════════════════
-- · 企微：入站帧不带昵称；靠 contact/users/search 返回的 name 补（无需新授权）。
-- · 飞书：入站/拉历史都不带昵称；靠通讯录 scope
--         （contact:user.basic_profile:readonly 等）反查，且受「应用通讯录可见范围」限制。
-- · 微信：iLink 没有通讯录能力 ⇒ 永远为空，UI 回退显示 peer_id。
-- ⇒ 允许 NULL：拿不到就是 NULL，UI 依次回退 nick_name → peer_name → peer_id。

ALTER TABLE im_chat ADD COLUMN nick_name TEXT;
