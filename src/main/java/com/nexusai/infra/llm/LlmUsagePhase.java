package com.nexusai.infra.llm;

/**
 * 一次 LLM 调用尝试的结局 · 决定该快照是「本轮账目主值」还是「额外开销」。
 *
 * <p><b>为什么需要区分</b>：流式失败后回退非流式时，上游可能对两次尝试都计费 ⇒ 明细行按尝试
 * 各落一行、账本求和时两次都计入（用户要求「流中断、取消、结束时也要统计实际开销」）。
 * 而常规路径只有一次尝试 ⇒ 只有 {@link #SETTLED} 一行。
 */
public enum LlmUsagePhase {

    /** 正常完成（onComplete / 非流式返回）。 */
    SETTLED,
    /** 被取消/中断（AbortController）—— 快照为中断时已累积的部分用量（上游可能已计费）。 */
    ABORTED,
    /** 失败（异常 / 流式回退前的那次尝试）—— 快照为失败时已累积的部分用量。 */
    FAILED
}
